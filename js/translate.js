// Function to change the language
function changeLanguage(languageCode, flagUrl) {
  // Get all elements with the 'data-translate' attribute
  const elements = document.querySelectorAll('[data-translate]');

  // Loop through the elements and update their text content based on the selected language
  elements.forEach(element => {
    const translationKey = element.getAttribute('data-translate');
    if (translations[languageCode] && translations[languageCode][translationKey]) {
      element.textContent = translations[languageCode][translationKey];
    }
  });

  // Update the selected language flag and text
  const selectedLangElement = document.querySelector('.selected-lang');
  selectedLangElement.innerHTML = `<img src="${flagUrl}" alt="Flag" class="flag"> ${languageCode.toUpperCase()}`;

  // Close the dropdown after changing the language
  toggleDropdown();
}

// Function to toggle the language dropdown
function toggleDropdown() {
  const dropdown = document.querySelector('.dropdown-content');
  dropdown.classList.toggle('show');
}

// Add event listener to close dropdown when clicking outside
window.addEventListener('click', function(event) {
  const dropdown = document.querySelector('.dropdown-content');
  if (!event.target.matches('.lang-btn') && !event.target.matches('.dropdown-content')) {
    dropdown.classList.remove('show');
  }
});

// Function to initialize the language
function initLanguage() {
  const defaultLanguage = 'en';
  changeLanguage(defaultLanguage, 'images/flags/en.png');
}

// Initialize the language on page load
window.onload = initLanguage;